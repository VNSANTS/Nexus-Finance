export function getIcon(nome: string | undefined, fallback: LucideIcon = HelpCircle): LucideIcon {
  if (!nome) return fallback
  return ICONES[nome] ?? fallback
}

interface IconProps extends LucideProps {
  name: string | undefined
  fallback?: LucideIcon
}

/** Uso: <Icon name={trilha.iconName} size={18} className="text-accent-cyan" /> */
export default function Icon({ name, fallback = HelpCircle, ...props }: IconProps) {
  const Componente = getIcon(name, fallback)
  return <Componente {...props} />
}

export { ICONES }
