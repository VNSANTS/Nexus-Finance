/**
 * Registro central de ícones.
 *
 * As telas usavam `import * as Icons from 'lucide-react'` e resolviam por
 * nome em runtime. Isso desliga o tree-shaking: o bundler não tem como saber
 * quais ícones você usa, então empacota a biblioteca inteira (~1.500 ícones).
 * Aqui os ícones realmente usados nos dados são importados nominalmente, e
 * o resto fica de fora do build.
 *
 * Para usar um ícone novo em `iconName`, importe-o e adicione ao mapa abaixo.
 */
